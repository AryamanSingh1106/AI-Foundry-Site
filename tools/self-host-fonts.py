#!/usr/bin/env python3
"""Download Inter and DM Mono from Google Fonts into assets/fonts and write css/fonts.css.

Why: the fonts then come from your own domain (one less connection, no third party, works offline).

Run it once, from the project folder, on a computer with internet:
    python3 tools/self-host-fonts.py

Then, in index.html, replace the two Google Fonts lines (the preload "as=style" link and the
<noscript> link) with:
    <link rel="stylesheet" href="css/fonts.css" />
    <link rel="preload" as="font" type="font/woff2" crossorigin href="assets/fonts/FILE.woff2" />
(the script prints the exact FILE names). You can also delete fonts.googleapis.com / fonts.gstatic.com
from the Content-Security-Policy in vercel.json.
"""
import os
import re
import sys
import urllib.request

CSS_URL = ("https://fonts.googleapis.com/css2?family=Inter:wght@400;600;900"
           "&family=DM+Mono:wght@400;500&display=swap")
# Google serves woff2 only to modern browsers, so we introduce ourselves as one.
UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36"
KEEP_SUBSETS = {"latin"}  # English only. Add "latin-ext" here if you need accented letters.


def parse_css(text):
    """Google's CSS -> list of dicts, one per @font-face, for the subsets we keep."""
    out = []
    for subset, body in re.findall(r"/\*\s*([a-z0-9-]+)\s*\*/\s*@font-face\s*\{([^}]*)\}", text):
        if subset not in KEEP_SUBSETS:
            continue
        get = lambda key: (re.search(key + r"\s*:\s*([^;]+);", body) or [None, ""])[1].strip()
        url = re.search(r"url\(([^)]+)\)", body)
        out.append({
            "family": get("font-family").strip("'\""),
            "weight": get("font-weight"),
            "style": get("font-style") or "normal",
            "range": get("unicode-range"),
            "url": url.group(1).strip("'\"") if url else "",
        })
    return out


def plan(faces):
    """Name each file once, even when several weights share one variable font file."""
    by_url = {}
    for f in faces:
        by_url.setdefault(f["url"], []).append(f)
    files = {}
    for url, group in by_url.items():
        fam = group[0]["family"].lower().replace(" ", "-")
        tag = "variable" if len(group) > 1 else group[0]["weight"]
        files[url] = f"{fam}-{tag}.woff2"
    return files


def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    req = urllib.request.Request(CSS_URL, headers={"User-Agent": UA})
    faces = parse_css(urllib.request.urlopen(req, timeout=30).read().decode("utf-8"))
    if not faces:
        sys.exit("Could not find any @font-face blocks. Google may have changed its format.")
    files = plan(faces)
    os.makedirs(os.path.join(root, "assets", "fonts"), exist_ok=True)
    for url, name in files.items():
        data = urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": UA}), timeout=30).read()
        with open(os.path.join(root, "assets", "fonts", name), "wb") as fh:
            fh.write(data)
        print(f"saved assets/fonts/{name} ({len(data) // 1024} KB)")
    css = ["/* generated by tools/self-host-fonts.py */"]
    for f in faces:
        css.append(
            "@font-face {\n"
            f"  font-family: \"{f['family']}\";\n  font-style: {f['style']};\n  font-weight: {f['weight']};\n"
            f"  font-display: swap;\n  src: url(\"../assets/fonts/{files[f['url']]}\") format(\"woff2\");\n"
            + (f"  unicode-range: {f['range']};\n" if f["range"] else "") + "}")
    with open(os.path.join(root, "css", "fonts.css"), "w") as fh:
        fh.write("\n".join(css) + "\n")
    print("wrote css/fonts.css")
    print("\nPreload these in index.html (the body font first):")
    for name in files.values():
        if name.startswith("inter"):
            print(f'  <link rel="preload" as="font" type="font/woff2" crossorigin href="assets/fonts/{name}" />')


if __name__ == "__main__":
    main()
